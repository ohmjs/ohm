func (node BareRuleNode) GenGoLeafInstAccepts(vc *genAcceptsCmd, tabs int) {
	longest := lo.MaxBy(node.Args, func(a, b NamedArgNode) bool {
		return len(a.Name) > len(b.Name)
	})
	for i, arg := range node.Args {
		padding := strings.Repeat(" ", len(longest.Name)-len(arg.Name))
		type_cast := arg.Node.GetBranch().GoType(vc.GenCmd.GoRuntimePackage)
		if type_cast == vc.GenCmd.GoRuntimePackage+".Node" {
			type_cast = ""
		} else {
			type_cast = ".(" + type_cast + ")"
		}
		vc.outf(`%[1]s%[2]s: %[3]skids[%[4]d]%[5]s,
`,
			strings.Repeat("\t", tabs),
			upper1st(arg.Name),
			padding,
			i,
			type_cast,
		)
	}
}

