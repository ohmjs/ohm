type genAcceptsCmd struct {
	GenCmd     genCmd `opts:"mode=embedded"`
	OutputFile string
	gmrsAst    GrammarsNode
}

func (vc *genAcceptsCmd) outf(format string, a ...any) {
	_, file, line, _ := runtime.Caller(1) // for line numbers to be correct when SuffixOutfLineNos is true
	parts := strings.Split(file, "/")
	parts = parts[len(parts)-2:]
	file = strings.Join(parts, "/")
	callerLine := fmt.Sprintf("%s:%d", file, line)
	f0 := format
	if vc.GenCmd.SuffixOutfLineNos {
		f0 = strings.ReplaceAll(format, "\n", fmt.Sprintf(" // %%[%d]s\n", len(a)+1))
		a = append(a, callerLine)
	}
	fmt.Fprintf(vc.GenCmd.sbldr, f0, a...)
}

func NewGenAcceptsCmd() *genAcceptsCmd {
	return &genAcceptsCmd{
		GenCmd: genCmd{
			GoRuntimeImport:   "github.com/ohmjs/goohm",
			GoRuntimePackage:  "goohm",
			sbldr:             &strings.Builder{},
			SuffixOutfLineNos: true,
		},
	}
}

func (vc *genAcceptsCmd) Run() error {
	if vc.GenCmd.Grammar[:1] == "@" {
		barr, err := os.ReadFile(vc.GenCmd.Grammar[1:])
		if err != nil {
			return fmt.Errorf("Error reading grammar file. %[1]v", err)
		}
		vc.GenCmd.Grammar = string(barr)
	}
	out, err := vc.Process()
	if err != nil {
		return err
	}
	if vc.OutputFile == "-" {
		fmt.Printf("%[1]s\n", out)
		return nil
	}
	fi, err := os.Create(vc.OutputFile)
	if err != nil {
		return fmt.Errorf("error creating file %[1]w", err)
	}
	defer fi.Close()
	_, err = fi.WriteString(out)
	if err != nil {
		return fmt.Errorf("error writing file %[1]w", err)
	}
	return nil
}

func (vc *genAcceptsCmd) Process() (string, error) {
	ctx := context.Background()
	var (
		gmr  *goohm.Grammar
		mr   *goohm.MatchResult
		err  error
		root goohm.Node
	)
	if gmr, err = goohm.NewGrammar(ctx, utils.OhmGrammarWasmBytes()); err != nil {
		return "", fmt.Errorf("creating grammar: %[1]v", err)
	}
	defer gmr.Close()
	if mr, err = gmr.Match(vc.GenCmd.Grammar); err != nil {
		return "", fmt.Errorf("matching: %[1]v", err)
	}
	defer mr.Close()
	if !mr.Succeeded() {
		return "", fmt.Errorf("match failed")
	}
	if root, err = mr.GetCstRoot(); err != nil {
		return "", fmt.Errorf("Error getting cst root. %[1]v", err)
	}
	gmrsAst, err := NewBuildGrammars(root).BuildRuleAst(root)
	if err != nil {
		return "", fmt.Errorf("Error building rule ast. %[1]v", err)
	}
	vc.gmrsAst = *gmrsAst
	vc.gmrsAst.GenGoAccepts(vc)
	return vc.GenCmd.sbldr.String(), nil
}

func (gmrs GrammarsNode) GenGoAccepts(vc *genAcceptsCmd) {
	if vc.GenCmd.GoTypePackage == "" {
		vc.GenCmd.GoTypePackage = strings.ToLower(gmrs.Gmr_names[0])
	}
	vc.outf(`// Code generated by ohmgo generate accepts - DO NOT EDIT.
package %[1]s

import (
	"%[2]s"
)

`, vc.GenCmd.GoTypePackage, vc.GenCmd.GoRuntimeImport)
	for _, gname := range gmrs.Gmr_names {
		vc.outf(`// accepts for grammar %[1]s

`, gname)
		gmr := gmrs.Grammars[gname]
		gmr.GenGoAccepts(vc)
	}
}

func (gmr GrammarNode) GenGoAccepts(vc *genAcceptsCmd) {
	vc.outf(`// TODO for grammar %[1]s, implement Make func for starting rule %[2]s

`,
		gmr.Name,
		gmr.Rule_names[0],
	)
	for _, rname := range gmr.Rule_names {
		rule := gmr.Rules[rname]
		branch := rule.GetBranch()
		vc.outf(`// Accept implementation for %[1]s%[2]s
//
`,
			branch.RuleName(),
			branch.Descr(" - ", ""),
		)
		for _, line := range branch.Source() {
			line = strings.TrimSpace(line)
			if line == "" {
				continue
			}
			vc.outf(`// %[1]s
`,
				line,
			)
		}
		vc.outf(`func (node *%[1]s[P, R]) Accept(this goohm.Node, visitor any, payload P) (result R, err error) {
	%[2]s.AssertName(this, "%[3]s")
	if v, ok := visitor.(Visitor_%[1]s[P, R]); ok {
		v.Visit%[1]s(node)
		return
	}
	if v, ok := visitor.(VisitorE_%[1]s[P, R]); ok {
		err = v.Visit%[1]s(node)
		return
	}
	if v, ok := visitor.(VisitorP_%[1]s[P, R]); ok {
		v.Visit%[1]s(node, payload)
		return
	}
	if v, ok := visitor.(VisitorPE_%[1]s[P, R]); ok {
		err = v.Visit%[1]s(node, payload)
		return
	}
	if v, ok := visitor.(VisitorR_%[1]s[P, R]); ok {
		result = v.Visit%[1]s(node)
		return
	}
	if v, ok := visitor.(VisitorRE_%[1]s[P, R]); ok {
		result, err = v.Visit%[1]s(node)
		return
	}
	if v, ok := visitor.(VisitorPR_%[1]s[P, R]); ok {
		result = v.Visit%[1]s(node, payload)
		return
	}
	if v, ok := visitor.(VisitorPRE_%[1]s[P, R]); ok {
		result, err = v.Visit%[1]s(node, payload)
		return
	}
	goohm.TypeCheckMethod[P, R](visitor, "%[1]s")
	return node.DefaultAccept(visitor, payload)
}

`,
			branch.TypeName(),
			vc.GenCmd.GoRuntimePackage,
			branch.RuleName(),
		)
		branch.GenGoAccepts(vc, gmr.Name)
	}
}

func (node VirtRuleNode) GenGoAccepts(vc *genAcceptsCmd, gmr_name string) {
	node0 := node.Node
	node0._BareRuleNode.Name = node.TypeName()
	node0.GenGoAccepts(vc, gmr_name)
}

func (node BareRuleNode) GenGoAccepts(vc *genAcceptsCmd, gmr_name string) {
	vc.outf(`func (node *%[1]s[P, R]) DefaultAccept(visitor any, payload P) (result R, err error) {
`,
		node.TypeName(),
	)
	longest := lo.MaxBy(node.Args, func(a, b NamedArgNode) bool {
		return len(a.Name) > len(b.Name)
	})
	for _, arg := range node.Args {
		padding := strings.Repeat(" ", len(longest.Name)-len(arg.Name))
		vc.outf(`	result, err =node.Accept%[1]s(visitor, payload)
`,
			r2name(arg.Name),
			padding,
			arg.Node.GetBranch().GoType(vc.GenCmd.GoRuntimePackage),
		)
	}
	vc.outf(`	return
}

`)
	for _, arg := range node.Args {
		vc.outf(`func (node *%[1]s[P, R]) Accept%[2]s(visitor any, payload P) (result R, err error) {
`,
			node.TypeName(),
			r2name(arg.Name),
		)
		arg.Node.GetBranch().GenGoLeafAccepts(vc, gmr_name, arg.Name)
		vc.outf(`	return
}

`)
	}
}

